<?php
/**
 * Build llms.txt files (https://llmstxt.org)
 *
 * Generates in the site root:
 *   llms.txt                  - index of the latest version (links to raw markdown pages)
 *   llms-full.txt             - complete content of the latest version in one file
 *   llms-{version}.txt        - index of every version (stable URL, also for the latest)
 *   llms-full-{version}.txt   - complete content of every version
 *   sitemap.xml               - rendered HTML pages of all published versions
 *   robots.txt                - references sitemap.xml and llms.txt (kept if maintained manually)
 *
 * Every page link points to the raw markdown file (/docs/{version}/{path}), which
 * Apache serves directly, so LLMs can fetch single pages without HTML noise.
 *
 * Run after adding, removing or renaming pages or versions.
 *
 * Usage: php build-llms.php [--base-url=https://docs.gorilla3d.de] [--latest=v1.5]
 *                           [--exclude=v1.0,v2.0] [--dry-run]
 */

require_once __DIR__ . '/config/config.php';

spl_autoload_register(function ($class) {
    $file = __DIR__ . '/classes/' . str_replace('\\', '/', $class) . '.php';
    if (file_exists($file)) {
        require_once $file;
    }
});

// --- Settings -----------------------------------------------------------------

$SITE_URL = 'https://docs.gorilla3d.de';

// Versions not published in llms files (sample docs of the doc framework, deprecated trees)
$EXCLUDE_VERSIONS = ['v1.0'];
$EXCLUDE_PATTERN  = '/deprecated/i';

// robots.txt is only (over)written if missing or still carrying this marker,
// remove the marker line to maintain the file manually
$ROBOTS_MARKER = '# Generated by build-llms.php';

// Project title, summary and notes: PROJECT_* constants in config/config.php

// --- Command line ---------------------------------------------------------------

$opts = getopt('', ['base-url:', 'latest:', 'exclude:', 'dry-run', 'help']);
if (isset($opts['help'])) {
    echo "Usage: php build-llms.php [--base-url=URL] [--latest=VERSION] [--exclude=V1,V2] [--dry-run]\n";
    exit(0);
}
if (isset($opts['base-url'])) {
    $SITE_URL = $opts['base-url'];
}
$SITE_URL = rtrim($SITE_URL, '/');
if (isset($opts['exclude'])) {
    $EXCLUDE_VERSIONS = array_merge($EXCLUDE_VERSIONS, array_map('trim', explode(',', $opts['exclude'])));
}
$dryRun = isset($opts['dry-run']);

// --- Helpers --------------------------------------------------------------------

function encodePath($path) {
    return implode('/', array_map('rawurlencode', explode('/', $path)));
}

function rawUrl($version, $path) {
    global $SITE_URL;
    return $SITE_URL . '/docs/' . rawurlencode($version) . '/' . encodePath($path);
}

function htmlUrl($version, $path) {
    global $SITE_URL;
    return $SITE_URL . '/version/' . rawurlencode($version) . '/page/' . encodePath($path);
}

function llmsFileName($version, $full) {
    return ($full ? 'llms-full-' : 'llms-') . $version . '.txt';
}

/** Makes relative image and page links absolute, so content works outside the site */
function absolutizeLinks($content, $version, $path) {
    global $SITE_URL;
    $pageDir = dirname($path);
    $pageDir = $pageDir === '.' ? '' : $pageDir;

    $rewrite = function ($url) use ($version, $pageDir, $SITE_URL) {
        if ($url === '' || $url[0] === '#' || preg_match('#^[a-z][a-z0-9+.-]*:#i', $url)) {
            return $url;
        }
        if ($url[0] === '/') {
            return $SITE_URL . $url;
        }
        // Same handling as MarkdownParser: data/ and docs/ are site root relative
        if (preg_match('#^(docs/|data/)#', $url)) {
            return $SITE_URL . '/' . $url;
        }
        // Relative link to another page of the same version
        $anchor = '';
        if (($pos = strpos($url, '#')) !== false) {
            $anchor = substr($url, $pos);
            $url = substr($url, 0, $pos);
        }
        $parts = [];
        foreach (explode('/', ($pageDir !== '' ? $pageDir . '/' : '') . $url) as $part) {
            if ($part === '' || $part === '.') continue;
            if ($part === '..') { array_pop($parts); continue; }
            $parts[] = rawurldecode($part);
        }
        return rawUrl($version, implode('/', $parts)) . $anchor;
    };

    $content = preg_replace_callback('/(\]\()\s*<?([^)\s>]+)>?((?:\s+"[^"]*")?\))/',
        function ($m) use ($rewrite) { return $m[1] . $rewrite($m[2]) . $m[3]; }, $content);
    $content = preg_replace_callback('/(<(?:img|a)\b[^>]*?\s(?:src|href)=")([^"]+)(")/i',
        function ($m) use ($rewrite) { return $m[1] . $rewrite($m[2]) . $m[3]; }, $content);
    return $content;
}

function buildIndex($version, $sections, $isLatest, $versions, $latest) {
    global $SITE_URL;

    $out  = "# " . PROJECT_TITLE . ($isLatest ? '' : " ($version)") . "\n\n";
    $out .= "> " . PROJECT_SUMMARY . "\n\n";
    $out .= "This index covers documentation version **$version**" . ($isLatest ? ' (latest)' : '') . ".\n";
    $out .= "Every link points to the raw Markdown source of a page (`$SITE_URL/docs/$version/{path}.md`).\n";
    $out .= "The rendered HTML page uses the same path including the `.md` extension:\n";
    $out .= "`$SITE_URL/version/$version/page/{path}.md`";
    if ($example = $sections[0]['pages'][0]['path'] ?? null) {
        $out .= ", e.g. `" . htmlUrl($version, $example) . "`";
    }
    $out .= ".\nThe complete documentation of this version in a single file:\n";
    $out .= "$SITE_URL/" . ($isLatest ? 'llms-full.txt' : llmsFileName($version, true)) . "\n\n";
    foreach (PROJECT_NOTES as $note) {
        $out .= "- $note\n";
    }
    $out .= "\n";

    foreach ($sections as $section) {
        $out .= "## {$section['title']}\n\n";
        foreach ($section['pages'] as $page) {
            $out .= "- [{$page['title']}](" . rawUrl($version, $page['path']) . ")";
            $out .= $page['description'] !== '' ? ": {$page['description']}\n" : "\n";
        }
        $out .= "\n";
    }

    $out .= "## Optional\n\n";
    $out .= "- [Complete documentation $version](" . $SITE_URL . '/' .
            ($isLatest ? 'llms-full.txt' : llmsFileName($version, true)) . "): All pages of this version in one file\n";
    if (!$isLatest) {
        $out .= "- [Latest version $latest]($SITE_URL/llms.txt): Index of the current documentation\n";
    }
    foreach ($versions as $other) {
        if ($other === $version || $other === $latest) continue;
        $out .= "- [Documentation $other]($SITE_URL/" . llmsFileName($other, false) .
                "): Index of version $other ([complete]($SITE_URL/" . llmsFileName($other, true) . "))\n";
    }
    return $out;
}

function buildFull($version, $sections, $isLatest) {
    global $SITE_URL;

    $out  = "# " . PROJECT_TITLE . " - complete content of version $version" . ($isLatest ? ' (latest)' : '') . "\n\n";
    $out .= "> " . PROJECT_SUMMARY . "\n\n";
    $out .= "Index: $SITE_URL/" . ($isLatest ? 'llms.txt' : llmsFileName($version, false)) . "\n";
    $out .= "Pages are separated by `---` lines and begin with their source URL.\n";

    foreach ($sections as $section) {
        foreach ($section['pages'] as $page) {
            $content = trim(absolutizeLinks($page['content'], $version, $page['path']));
            $out .= "\n---\n\n";
            $out .= "Source: " . rawUrl($version, $page['path']) . "\n";
            $out .= "Section: {$section['title']}\n\n";
            $out .= $content . "\n";
        }
    }
    return $out;
}

/** Sitemap with the rendered HTML pages of all published versions, latest first */
function buildSitemap($pagesByVersion, $latest) {
    global $SITE_URL;

    $xml = function ($s) { return htmlspecialchars($s, ENT_XML1 | ENT_QUOTES, 'UTF-8'); };
    $out  = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n";
    $out .= "<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n";
    $out .= "  <url><loc>" . $xml($SITE_URL . '/') . "</loc></url>\n";
    foreach ($pagesByVersion as $version => $paths) {
        foreach ($paths as $path) {
            $out .= "  <url><loc>" . $xml(htmlUrl($version, $path)) . "</loc>";
            $mtime = @filemtime(DOCS_PATH . '/' . $version . '/' . $path);
            if ($mtime) {
                $out .= "<lastmod>" . gmdate('Y-m-d', $mtime) . "</lastmod>";
            }
            $out .= "<priority>" . ($version === $latest ? '0.8' : '0.3') . "</priority></url>\n";
        }
    }
    $out .= "</urlset>\n";
    return $out;
}

function buildRobots() {
    global $SITE_URL, $ROBOTS_MARKER;
    return "$ROBOTS_MARKER\n" .
           "# Documentation for LLMs: $SITE_URL/llms.txt (complete: $SITE_URL/llms-full.txt)\n\n" .
           "User-agent: *\n" .
           "Disallow: /api/\n" .
           "Allow: /\n\n" .
           "Sitemap: $SITE_URL/sitemap.xml\n";
}

function writeFile($file, $content, $dryRun) {
    $status = !file_exists($file) ? 'created' :
              (file_get_contents($file) === $content ? 'unchanged' : 'updated');
    if (!$dryRun && $status !== 'unchanged') {
        file_put_contents($file, $content);
    }
    printf("  %-9s %s (%s KB)\n", $status, basename($file), number_format(strlen($content) / 1024, 1));
}

// --- Main -----------------------------------------------------------------------

$versions = [];
foreach (DocumentationManager::getVersions() as $v) {
    if (in_array($v['name'], $EXCLUDE_VERSIONS, true) || preg_match($EXCLUDE_PATTERN, $v['name'])) continue;
    $versions[] = $v['name']; // newest first
}
if (!$versions) {
    fwrite(STDERR, "No versions found in docs/.\n");
    exit(1);
}

$latest = $opts['latest'] ?? $versions[0];
if (!in_array($latest, $versions, true)) {
    fwrite(STDERR, "Version '$latest' not found. Available: " . implode(', ', $versions) . "\n");
    exit(1);
}

echo "Building llms files for $SITE_URL (latest: $latest)" . ($dryRun ? ' [dry run]' : '') . "\n";

$written = [];
$pagesByVersion = [];
foreach ($versions as $version) {
    $isLatest = $version === $latest;
    $sections = DocIndex::collectSections(DocumentationManager::getFileTree($version), $version);
    foreach ($sections as $section) {
        foreach ($section['pages'] as $page) {
            $pagesByVersion[$version][] = $page['path'];
        }
    }
    $count = array_sum(array_map(function ($s) { return count($s['pages']); }, $sections));
    echo "\n$version: $count pages\n";

    // Every version gets its stable versioned files, the latest additionally llms.txt / llms-full.txt
    $files = [
        llmsFileName($version, false) => buildIndex($version, $sections, false, $versions, $latest),
        llmsFileName($version, true)  => buildFull($version, $sections, false),
    ];
    if ($isLatest) {
        $files['llms.txt']      = buildIndex($version, $sections, true, $versions, $latest);
        $files['llms-full.txt'] = buildFull($version, $sections, true);
    }
    foreach ($files as $name => $content) {
        writeFile(BASE_PATH . '/' . $name, $content, $dryRun);
        $written[] = $name;
    }
}

// Remove files of versions that no longer exist
foreach (glob(BASE_PATH . '/llms-*.txt') as $file) {
    if (!in_array(basename($file), $written, true)) {
        echo "  removed   " . basename($file) . "\n";
        if (!$dryRun) unlink($file);
    }
}

// Sitemap and robots.txt (latest version first)
echo "\nsite files\n";
$pagesByVersion = [$latest => $pagesByVersion[$latest]] + $pagesByVersion;
writeFile(BASE_PATH . '/sitemap.xml', buildSitemap($pagesByVersion, $latest), $dryRun);

$robotsFile = BASE_PATH . '/robots.txt';
if (file_exists($robotsFile) && strpos(file_get_contents($robotsFile), $ROBOTS_MARKER) === false) {
    echo "  skipped   robots.txt (maintained manually)\n";
} else {
    writeFile($robotsFile, buildRobots(), $dryRun);
}

echo "\nDone.\n";
